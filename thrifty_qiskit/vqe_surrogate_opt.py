"""
vqe_surrogate_opt.py -- Surrogate models of the VQE energy landscape.

One VQE energy evaluation is expensive (many shots, queue time).  Instead of
treating E(theta) as a black box, exploit what is known about it:

(1) Rotosolve (Ostaszewski, Grant, Benedetti 2021; Nakanishi, Fujii, Todo 2020)
    Every parameter enters through a single Pauli rotation, so along each
    coordinate E(theta_k) = A cos(theta_k - B) + C exactly.  Three evaluations
    determine (A, B, C); the coordinate minimum is then analytic.
    This is a Fourier-series surrogate per direction.

(2) Parameter-shift gradients + gradient descent (baseline with exact gradients).

(3) Gaussian-process Bayesian optimisation
    Global surrogate E(theta) ~ GP with a periodic kernel on the angles;
    expected improvement chooses the next evaluation.  Suits low dimension.

(4) COBYLA / random search baselines.

Every optimiser is charged per circuit evaluation through `VQEProblem`, so
"cost" always means number of circuit executions, not wall time.

Data: none needed.  The landscape is generated by the circuit itself
(Statevector = exact, or shots via StatevectorEstimator).
"""

from __future__ import annotations

from typing import Callable, Dict, Optional, Tuple

import numpy as np
from scipy.optimize import minimize
from scipy.stats import norm


# ************************************************************
# Problem: TFIM ground state with a hardware-efficient ansatz
# ************************************************************
class VQEProblem:
    def __init__(self, n: int = 4, reps: int = 1, J: float = 1.0, h: float = 1.0,
                 shots: Optional[int] = None, seed: int = 0):
        from qiskit.circuit.library import real_amplitudes
        from qiskit.quantum_info import SparsePauliOp

        self.n, self.shots, self.seed = n, shots, seed
        self.ansatz = real_amplitudes(n, reps=reps, entanglement="linear")
        self.dim = self.ansatz.num_parameters
        terms = [("ZZ", [i, i + 1], -J) for i in range(n - 1)] + [("X", [i], -h) for i in range(n)]
        self.H = SparsePauliOp.from_sparse_list(terms, num_qubits=n)
        self.exact_E0 = float(np.linalg.eigvalsh(self.H.to_matrix())[0])
        self.n_evals = 0
        self.log = []                      # (n_evals, energy) for every evaluation
        self._rng = np.random.default_rng(seed)
        self._H2 = self.H @ self.H

    def energy(self, theta: np.ndarray) -> float:
        """<H>; with `shots`, Gaussian noise of std sqrt(Var(H)/shots) is added
        (idealised model of measuring H with `shots` samples)."""
        from qiskit.quantum_info import Statevector
        self.n_evals += 1
        sv = Statevector(self.ansatz.assign_parameters(theta))
        e = float(np.real(sv.expectation_value(self.H)))
        if self.shots is not None:
            var = float(np.real(sv.expectation_value(self._H2))) - e ** 2
            e += self._rng.normal(0, np.sqrt(max(var, 0) / self.shots))
        self.log.append((self.n_evals, e))
        return e

    def reset(self) -> None:
        self.n_evals, self.log = 0, []

    def energies(self, thetas: np.ndarray) -> np.ndarray:
        return np.array([self.energy(t) for t in thetas])


# ************************************************************
# (1) Rotosolve: exact sinusoidal surrogate per coordinate
# ************************************************************
def sinusoid_fit(e0: float, ep: float, em: float) -> Tuple[float, float, float]:
    """
    Given E(t), E(t+pi/2), E(t-pi/2) for E(x) = A cos(x - t - B) + C  (frequency 1),
    return (A, B, C) with B measured relative to t.
    """
    C = 0.5 * (ep + em)
    A = np.hypot(e0 - C, 0.5 * (ep - em))
    B = np.arctan2(0.5 * (ep - em), e0 - C)    # E(x)=A cos(x-B)+C, x relative to t
    return A, B, C


def rotosolve(prob: VQEProblem, theta0: np.ndarray, n_sweeps: int = 5,
              tol: float = 1e-8) -> Tuple[np.ndarray, np.ndarray]:
    """Coordinate-wise analytic minimisation; 2 new evaluations per parameter per sweep."""
    theta = theta0.copy()
    e0 = prob.energy(theta)
    hist, evals = [e0], [prob.n_evals]
    for _ in range(n_sweeps):
        e_start = e0
        for k in range(prob.dim):
            tp = theta.copy(); tp[k] += np.pi / 2
            tm = theta.copy(); tm[k] -= np.pi / 2
            ep, em = prob.energy(tp), prob.energy(tm)
            A, B, C = sinusoid_fit(e0, ep, em)
            theta[k] += B + np.pi          # cos(x - B) = -1  at x = B + pi
            e0 = C - A                     # exact new energy, no circuit needed
            hist.append(e0); evals.append(prob.n_evals)
        if e_start - e0 < tol:
            break
    prob.rotosolve_curve = (np.array(evals), np.array(hist))
    return theta, np.array(hist)


# ************************************************************
# (2) Parameter-shift gradient descent
# ************************************************************
def parameter_shift_grad(prob: VQEProblem, theta: np.ndarray) -> np.ndarray:
    g = np.empty(prob.dim)
    for k in range(prob.dim):
        tp = theta.copy(); tp[k] += np.pi / 2
        tm = theta.copy(); tm[k] -= np.pi / 2
        g[k] = 0.5 * (prob.energy(tp) - prob.energy(tm))
    return g


def gradient_descent(prob: VQEProblem, theta0: np.ndarray, lr: float = 0.2,
                     n_iter: int = 100) -> Tuple[np.ndarray, np.ndarray]:
    theta = theta0.copy()
    hist = [prob.energy(theta)]
    for _ in range(n_iter):
        theta -= lr * parameter_shift_grad(prob, theta)
        hist.append(prob.energy(theta))
    return theta, np.array(hist)


# ************************************************************
# (3) GP Bayesian optimisation with periodic kernel
# ************************************************************
class PeriodicGP:
    """GP on angles: k(a,b) = s^2 exp(-sum_k 2 sin^2((a_k-b_k)/2) / l^2)."""

    def __init__(self, length: float = 1.0, signal: float = 1.0, noise: float = 1e-4):
        self.l, self.s, self.noise = length, signal, noise

    def _k(self, A: np.ndarray, B: np.ndarray) -> np.ndarray:
        d = A[:, None, :] - B[None, :, :]
        return self.s ** 2 * np.exp(-np.sum(2 * np.sin(d / 2) ** 2, axis=-1) / self.l ** 2)

    def fit(self, X: np.ndarray, y: np.ndarray) -> "PeriodicGP":
        self.X, self.mu, self.sd = X, y.mean(), y.std() + 1e-12
        K = self._k(X, X) + self.noise * np.eye(len(X))
        self.Lc = np.linalg.cholesky(K)
        self.alpha = np.linalg.solve(self.Lc.T, np.linalg.solve(self.Lc, (y - self.mu) / self.sd))
        return self

    def predict(self, Xs: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
        Ks = self._k(Xs, self.X)
        m = Ks @ self.alpha
        v = np.linalg.solve(self.Lc, Ks.T)
        var = np.clip(self.s ** 2 - np.sum(v ** 2, axis=0), 1e-12, None)
        return self.mu + self.sd * m, self.sd * np.sqrt(var)


def bayesian_optimisation(prob: VQEProblem, n_init: int = 10, n_iter: int = 60,
                          n_cand: int = 4000, length: float = 1.2,
                          rng: Optional[np.random.Generator] = None) -> Tuple[np.ndarray, np.ndarray]:
    rng = rng or np.random.default_rng(0)
    X = rng.uniform(0, 2 * np.pi, (n_init, prob.dim))
    y = prob.energies(X)
    hist = list(np.minimum.accumulate(y))
    for _ in range(n_iter):
        gp = PeriodicGP(length=length).fit(X, y)
        best = y.min()
        # candidates: global random + local perturbations of the incumbent
        cand = np.vstack([rng.uniform(0, 2 * np.pi, (n_cand // 2, prob.dim)),
                          X[np.argmin(y)] + rng.normal(0, 0.5, (n_cand // 2, prob.dim))])
        m, s = gp.predict(cand)
        z = (best - m) / s
        ei = (best - m) * norm.cdf(z) + s * norm.pdf(z)
        x_next = cand[np.argmax(ei)]
        y_next = prob.energy(x_next)
        X = np.vstack([X, x_next]); y = np.append(y, y_next)
        hist.append(min(hist[-1], y_next))
    return X[np.argmin(y)], np.array(hist)


# ************************************************************
# (4) Baselines
# ************************************************************
def cobyla(prob: VQEProblem, theta0: np.ndarray, maxiter: int = 300) -> Tuple[np.ndarray, np.ndarray]:
    hist = []
    res = minimize(lambda t: (hist.append(prob.energy(t)) or hist[-1]), theta0,
                   method="COBYLA", options={"maxiter": maxiter})
    return res.x, np.minimum.accumulate(np.array(hist))


def random_search(prob: VQEProblem, n: int, rng: Optional[np.random.Generator] = None):
    rng = rng or np.random.default_rng(0)
    X = rng.uniform(0, 2 * np.pi, (n, prob.dim))
    y = prob.energies(X)
    return X[np.argmin(y)], np.minimum.accumulate(y)


# ************************************************************
# Demo: circuit evaluations needed to reach E_target + tol
# ************************************************************
def evals_to_reach(prob: VQEProblem, target: float, curve=None) -> Optional[int]:
    if curve is None:
        ev = np.array([e for e, _ in prob.log]); en = np.array([x for _, x in prob.log])
    else:
        ev, en = curve
    hit = np.where(en <= target)[0]
    return int(ev[hit[0]]) if len(hit) else None


if __name__ == "__main__":
    prob = VQEProblem(n=4, reps=2, h=1.0)
    rng = np.random.default_rng(0)
    theta0 = rng.uniform(0, 2 * np.pi, prob.dim)
    # reachable minimum of this ansatz (multi-start reference, not charged)
    ref = VQEProblem(n=4, reps=2, h=1.0)
    E_ans = min(cobyla(ref, np.random.default_rng(s).uniform(0, 2 * np.pi, ref.dim), 3000)[1][-1]
                for s in range(6))
    tol = 0.05
    print(f"TFIM n=4, {prob.dim} params.  exact E0={prob.exact_E0:.4f}, ansatz min~{E_ans:.4f}, "
          f"target = ansatz min + {tol}")
    print(f"{'method':24s} {'evals used':>10s} {'best E':>10s} {'evals to target':>16s}")

    def report(name, fn, curve_attr=None):
        prob.reset()
        fn()
        curve = getattr(prob, curve_attr) if curve_attr else None
        best = min(x for _, x in prob.log) if curve is None else curve[1].min()
        n = evals_to_reach(prob, E_ans + tol, curve)
        print(f"{name:24s} {prob.n_evals:10d} {best:10.4f} {str(n) if n else 'not reached':>16s}")

    report("Rotosolve (30 sweeps)", lambda: rotosolve(prob, theta0, n_sweeps=30), "rotosolve_curve")
    report("param-shift GD (40)", lambda: gradient_descent(prob, theta0, lr=0.3, n_iter=40))
    report("COBYLA (600)", lambda: cobyla(prob, theta0, maxiter=600))
    report("GP-BO (10+150)", lambda: bayesian_optimisation(prob, 10, 150, rng=np.random.default_rng(1)))
    report("random search (160)", lambda: random_search(prob, 160, np.random.default_rng(1)))

    print("\nWith shot noise (4096 shots per evaluation), exact energy of the returned point:")
    probs = VQEProblem(n=4, reps=2, h=1.0, shots=4096)
    for name, fn in [("Rotosolve (30 sweeps)", lambda: rotosolve(probs, theta0, n_sweeps=30)),
                     ("COBYLA (600)", lambda: cobyla(probs, theta0, maxiter=600)),
                     ("GP-BO (10+150)", lambda: bayesian_optimisation(probs, 10, 150, rng=np.random.default_rng(1)))]:
        probs.reset()
        th, _ = fn()
        E_true = VQEProblem(n=4, reps=2, h=1.0).energy(th)
        print(f"{name:24s} {probs.n_evals:10d} exact E = {E_true:.4f}  (E - ansatz min = {E_true - E_ans:.2e})")
